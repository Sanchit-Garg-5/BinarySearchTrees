/*tc is o(n) and sc is o(h)
for a given preorder of a valid bst, if ele<me: that means it is to be added to my left. no need to check if it
less than my ancestors or not(because its a valid preorder of a valid bst).
BUT BUT
ele>me: DOESN'T mean it WILL DEFINITELY go to my right,rather check my ancestors. if ele>ancestor-then it goes to their right not mine.
so maintain a prev. when ele added to left, it receieves me as prev. but if ele addded to right, it recevies my prev as its prev. 
SO IT KNOWS IF ELE IS GREATER THAN DADA JI OR NOT.
*/
void preorder(Node* prev,vector<ll>&given,int& i,Node* curr){
    if(i>=given.size()){return;}
    if(given[i]<curr->data){
        Node* temp=new Node(given[i]); 
        curr->left=temp; i++;
        preorder(curr,given,i,temp); // dont pass i++ or i+1: as doing so only passes a temporary increased value. we need the i to actually change.
//don't return here yet. let us say some ele was greater than me and my left child.
//so the just above statement (that is my left child)-would return to me, and if i were to
//return at this moment:then who would put ele?
    } 
    if(i>=given.size()){return;} // check again if any element left or not:
//because what if all were smaller than root (for ex).
    if(!prev || prev->data>given[i]){
        Node* temp=new Node(given[i]); 
        curr->right=temp; i++;
        preorder(prev,given,i,temp); // dont pass i++ or i+1: as doing so only passes a temporary increased value. we need the i to actually change.
    }
    return; 
}

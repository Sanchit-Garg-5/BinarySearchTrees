Node* ceil_search(Node* curr, ll val){
    if(!curr){return nullptr;} ll cval=curr->data;
    if(val==cval){return curr;}
    if(val<cval){
        Node* temp=ceil_search(curr->left,val);
        if(temp){return temp;}  return curr;
    }
    return ceil_search(curr->right,val);
}

class Node{
    public:
    ll data;
    Node* left; 
    Node* right;
    Node(ll val, Node* left1, Node* right1):data(val),left(left1),right(right1){}
    Node(ll val):data(val),left(nullptr),right(nullptr){}
    Node():data(0),left(nullptr),right(nullptr){}
};
/*given a val, search for the largest node<=val.
*/
/*tc is avg o(log base2 n)(balanced) and worse of o(n)if degenrate/skewed
and sc depends if recursive o(h) else o(1) iterative
*/
Node* floor_search(Node* curr, ll val){
    if(!curr){return nullptr;} ll cval=curr->data;
    if(val==cval){return curr;}
    if(val<cval){
        return floor_search(curr->left,val);
        
    }
    Node* temp=floor_search(curr->right,val);
    if(temp){return temp;} return curr;
}

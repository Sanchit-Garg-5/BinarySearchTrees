void lca(Node* curr,Node*& ans,ll a,ll b){ 
    if(ans || !curr){return;}
    if(curr->data>=a && curr->data<=b){ans=curr; return;}
    if(a<curr->data){lca(curr->left,ans,a,b); return;}
    lca(curr->right,ans,a,b); return;
}
